"""Every pattern at agentic-patterns.com, and the primitives it is built from.

The evidence behind docs/97-PRIMITIVES.md section 5.4 and Appendix B. It loads
the snapshot of the site's catalogue taken on 2026-11-10 (203 patterns,
research/extracts/agentic-patterns-2026-11-10.json), gives every pattern a
recipe in the seven primitives, and refuses to finish if a pattern in the
snapshot has no recipe or a recipe names a pattern that is not in the snapshot.
A pattern the site adds is therefore a failure here until someone decides what
it is made of, rather than a pattern that silently went uncounted.

    python3 scripts/pattern-coverage.py            # counts
    python3 scripts/pattern-coverage.py --table    # one row per pattern
    python3 scripts/pattern-coverage.py --kind practice   # one kind only

Every pattern gets a construction. Each also carries a kind that says where
the construction's edge is:

  mechanism  Everything the pattern does runs inside the agent. 175 of the 203.
  training   The construction is the pipeline (dataset Store, grader Check,
             trainer Actor, catalogue write under law 8). The weight update
             happens inside the trainer Actor, the way a payment happens inside
             the payments tool. 7 of the 203.
  practice   The construction is the pattern's mechanical part (a port, a gate,
             a Store, a release rule); the decision that the pattern is really
             about is taken by people outside any runtime. 18 of the 203.
  pact       The construction is a PACT tree. 3 of the 203.

Three checks run on every recipe, and the script fails if any fails:

  1. Every pattern in the snapshot has a recipe, and no recipe is orphaned.
  2. Every operation a recipe names is in OPS, the closed operation vocabulary
     of the seven primitives (docs/97-PRIMITIVES.md section 2 and 5.4). A
     recipe is therefore typed against the kernel, not free prose.
  3. Every operation in OPS is used by at least one pattern. An operation no
     pattern needs would be a candidate for removal.

OPS is read from spec/kernel.yaml, which also records, for each operation, the
PACT keyword that is that operation today. `--ops` prints it, with the fields
of spec/schema.yaml whose `kernel-op:` names it.
`--check-shipped` runs `pact check` on every shipped example a recipe cites.
"""
