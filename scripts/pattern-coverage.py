def main(argv):
    pats = json.loads(SNAPSHOT.read_text())["patterns"]
    slugs = {p["slug"] for p in pats}
    missing = sorted(slugs - set(R)); extra = sorted(set(R) - slugs)
    assert not missing and not extra, (missing, extra)
    # check 2: every operation a recipe names is in the kernel; check 3: every kernel op is used
    assert set(O) == set(R), (set(O) ^ set(R))
    used = collections.Counter()
    for slug, ops in O.items():
        for op in ops.split():
            assert op in OPS, (slug, op)
            used[op] += 1
    unused = sorted(set(OPS) - set(used)); assert not unused, unused
    for slug, path in SHIPPED.items():
        assert slug in R, slug
        assert (SNAPSHOT.parent.parent.parent / path).exists(), path
    kinds = collections.Counter(k for k,_,_ in R.values())
    prim = collections.Counter(); first = collections.Counter()
    for k,ps,_ in R.values():
        parts = ps.split("+"); first[parts[0]] += 1
        for p in parts: prim[p] += 1
    print("patterns in snapshot:", len(pats), "recipes:", len(R), "unmapped:", len(missing))
    print("kernel operations:", len(OPS), "all used; proposed (no keyword yet):", sum(1 for v in OPS.values() if "proposed" in v[2]))
    print("shipped PACT artifacts cited:", len(SHIPPED), "covering", len(set(SHIPPED)), "patterns")
    print("by kind:", dict(kinds.most_common()))
    print("main primitive:", dict(first.most_common()))
    print("any part:", dict(prim.most_common()))
    bycat = collections.defaultdict(collections.Counter)
    for p in pats: bycat[p["category"]][R[p["slug"]][0]] += 1
    for c in sorted(bycat): print(f"  {c}: {dict(bycat[c])}")
    if "--ops" in argv:
        fields = collections.defaultdict(list)
        schema = yaml.safe_load((SNAPSHOT.parent.parent.parent / "spec/schema.yaml").read_text())
        for g, gv in schema["groups"].items():
            for f, fv in (gv.get("fields") or {}).items():
                ops = fv.get("kernel-op", []) if isinstance(fv, dict) else []
                for op in [ops] if isinstance(ops, str) else ops: fields[op].append(f"{g}.{f}")
        print("\n| Operation | Primitive | What it does | PACT keyword today | Fields |\n|---|---|---|---|---|")
        for k,(prim,what,kw) in OPS.items(): print(f"| `{k}` | {prim} | {what} | {kw} | {', '.join(f'`{x}`' for x in fields[k])} |")
    if "--check-shipped" in argv:
        import subprocess, shutil
        root = SNAPSHOT.parent.parent.parent
        pact = max((root / c for c in ("target/release/pact","target/debug/pact") if (root / c).exists()), key=lambda b: b.stat().st_mtime, default=None)  # the newest build, never a stale one
        assert pact, "build pact first: cargo build --bin pact"
        for path in sorted(set(SHIPPED.values())):
            target = root / path
            if target.is_file() or not (target / "workspace.yaml").exists():
                # a file, or a folder inside a workspace: find the workspace that holds it and check that
                ws = target if target.is_dir() else target.parent
                while ws != root and not (ws / "workspace.yaml").exists(): ws = ws.parent
                if ws == root:
                    print(f"  {path}: a stock loop, loaded by every workspace that names it; checked via examples/refund-desk"); continue
                target = ws
            r = subprocess.run([str(pact), "check", str(target), "--quiet"], capture_output=True, text=True)
            print(f"  {path}: {'OK' if r.returncode == 0 else 'FAILED'}")
            assert r.returncode == 0, r.stdout + r.stderr
    only = None
    if "--kind" in argv: only = argv[argv.index("--kind")+1]
    if "--table" in argv or only:
        pats.sort(key=lambda p: (p["category"], p["title"]))
        cat = None
        for p in pats:
            k, ps, recipe = R[p["slug"]]
            if only and k != only: continue
            if p["category"] != cat:
                cat = p["category"]; print(f"\n**{cat}**\n\n| Pattern | Kind | Built from | Recipe | Operations | Shipped |\n|---|---|---|---|---|---|")
            ops = ", ".join(f"`{o}`" for o in dict.fromkeys(O[p["slug"]].split()))
            sh = f"`{SHIPPED[p['slug']]}`" if p["slug"] in SHIPPED else ""
            print(f"| {p['title']} | {k} | {ps.replace('+', ' + ')} | {recipe} | {ops} | {sh} |")

if __name__ == "__main__":
    main(sys.argv[1:])
